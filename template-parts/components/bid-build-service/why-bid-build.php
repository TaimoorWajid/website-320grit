    <div class="faq-bid__header">
      <div class="faq-bid__eyebrow">07 — QUESTIONS</div>
      <h2 class="faq-bid__title">FREQUENTLY<br><span>ASKED QUESTIONS</span></h2>
      <p class="faq-bid__desc">
        Everything you need to know about working with 320 GRIT on a Bid-Build project.
      </p>
    </div>

    <div class="faq-bid__list">

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>What is the Bid-Build delivery method?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            Bid-Build (also called Design-Bid-Build) is a sequential delivery method. The owner first completes the full design with their architect and engineers. Once the documents are finished, the project is put out for competitive bids from qualified general contractors. The selected contractor then builds the project according to the completed plans and specifications.
          </p>
        </div>
      </div>

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>When is Bid-Build the best choice?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            Bid-Build works best when the design is complete or nearly complete, the owner wants maximum price competition, and the project scope is clearly defined. It is also the required method for many publicly funded projects. It gives owners strong cost transparency and clear contractual separation between design and construction.
          </p>
        </div>
      </div>

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>How does 320 GRIT manage the competitive bidding process?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            We prequalify contractors, prepare clear bid packages, manage the bid period, evaluate proposals on both price and qualifications, and provide a transparent recommendation. Our goal is to deliver the best overall value — not simply the lowest number.
          </p>
        </div>
      </div>

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>Can 320 GRIT work with my existing architect and engineers?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            Yes. In the Bid-Build method the design team is typically selected by the owner. We coordinate closely with your architect and consultants throughout the bidding and construction phases to protect design intent and ensure smooth execution.
          </p>
        </div>
      </div>

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>How are costs controlled during a Bid-Build project?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            Cost control begins with a complete and coordinated set of documents before bidding. During construction we maintain rigorous change-order management, real-time cost tracking, and clear communication so the owner always knows the financial status of the project.
          </p>
        </div>
      </div>

      <div class="faq-bid__item">
        <button class="faq-bid__question" aria-expanded="false">
          <span>How do you manage the construction schedule?</span>
          <span class="faq-bid__icon"></span>
        </button>
        <div class="faq-bid__answer">
          <p>
            We develop a detailed baseline schedule, track progress weekly, identify risks early, and maintain open communication with all parties. Our focus is disciplined execution so the project stays on track from notice to proceed through final handover.
          </p>
        </div>
      </div>

